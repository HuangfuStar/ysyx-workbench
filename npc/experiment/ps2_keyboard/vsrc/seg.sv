module seg7_hex(
    input  [3:0] x,
    output [7:0] seg
);
    assign seg =
        (x == 4'h0) ? 8'b00000011 :
        (x == 4'h1) ? 8'b10011111 :
        (x == 4'h2) ? 8'b00100101 :
        (x == 4'h3) ? 8'b00001101 :
        (x == 4'h4) ? 8'b10011001 :
        (x == 4'h5) ? 8'b01001001 :
        (x == 4'h6) ? 8'b01000001 :
        (x == 4'h7) ? 8'b00011111 :
        (x == 4'h8) ? 8'b00000001 :
        (x == 4'h9) ? 8'b00001001 :
        (x == 4'hA) ? 8'b00010001 :
        (x == 4'hB) ? 8'b11000001 :
        (x == 4'hC) ? 8'b01100011 :
        (x == 4'hD) ? 8'b10000101 :
        (x == 4'hE) ? 8'b01100001 :
                    8'b01110001;
endmodule
